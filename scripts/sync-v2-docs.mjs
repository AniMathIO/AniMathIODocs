#!/usr/bin/env node
// Adapts the reference pages of the AniMathIO 2 docs from the main AniMathIO repository (branch `main`) into docs/. The generated pages are committed, so `npm run build` never needs
// the other checkout. Hand-written pages (getting started, install, editor tour, math objects,
// captions and automation) are not touched.
//
//   node scripts/sync-v2-docs.mjs --source ../AniMathIO [--ref main] [--images]
//
// --source  a checkout of AniMathIO/AniMathIO at the commit to document
// --ref     git ref used for links into the source repository (default main)
// --images  also crop and convert docs/screenshots/*.png to static/img/v2/*.webp (needs ImageMagick)
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';

const args = process.argv.slice(2);
const opt = (name, fallback) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : fallback;
};
const source = resolve(opt('--source', '../AniMathIO'));
const ref = opt('--ref', 'main');
const repoBlob = `https://github.com/AniMathIO/AniMathIO/blob/${ref}`;
const out = resolve('docs');

/** Source file, output slug, sidebar position, title and description. */
const pages = [
  ['keyboard-shortcuts.md', 'keyboard-shortcuts', 6, 'Keyboard shortcuts', 'The Premiere Pro style default keymap.'],
  ['plugins.md', 'plugins', 7, 'Plugin authoring', 'Write a sandboxed WebAssembly plugin: WIT world, host imports, manifest, sandbox limits.'],
  ['cli.md', 'cli', 8, 'CLI reference', 'Every animathio-cli subcommand, generated from --help.'],
  ['mcp.md', 'mcp', 9, 'Control protocol and MCP', 'The local control socket and the MCP tool surface.'],
  ['architecture.md', 'architecture', 10, 'Architecture', 'Crate map, layering, the time model and the data flow.'],
  ['migrating-from-v1.md', 'migrating-from-v1', 11, 'Migrating from 1.x', 'What maps from AniMathIO 1.x projects, and the known gaps.'],
];
const slugs = new Map(pages.map(([file, slug]) => [file, slug]));

function rewriteLinks(text) {
  return text.replace(/\]\(([^)\s]+)\)/g, (whole, target) => {
    if (/^(https?:|mailto:|#)/.test(target)) return whole;
    const [path, hash = ''] = target.split('#');
    const anchor = hash ? `#${hash}` : '';
    if (path.startsWith('screenshots/')) {
      return `](/img/v2/${basename(path).replace(/\.png$/, '.webp')})`;
    }
    if (slugs.has(path)) return `](./${slugs.get(path)}${anchor})`;
    // Anything else points into the source repository: resolve against docs/.
    const resolved = join('docs', path).split('\\').join('/');
    return `](${repoBlob}/${resolved}${anchor})`;
  });
}

mkdirSync(out, { recursive: true });
for (const [file, slug, position, title, description] of pages) {
  let body = readFileSync(join(source, 'docs', file), 'utf8');
  body = body.replace(/^# .*\n+/, '');
  body = rewriteLinks(body);
  const front = [
    '---',
    `title: ${JSON.stringify(title)}`,
    `sidebar_label: ${JSON.stringify(title)}`,
    `sidebar_position: ${position}`,
    `description: ${JSON.stringify(description)}`,
    '---',
    '',
    `<!-- Generated by scripts/sync-v2-docs.mjs from docs/${file} in AniMathIO/AniMathIO. Do not edit here: change the source and re-run the script. -->`,
    '',
    `# ${title}`,
    '',
    '',
  ].join('\n');
  writeFileSync(join(out, `${slug}.md`), front + body);
  console.log(`docs/${slug}.md`);
}

if (args.includes('--images')) {
  const shots = join(source, 'docs/screenshots');
  const dest = resolve('static/img/v2');
  mkdirSync(dest, { recursive: true });
  for (const file of readdirSync(shots).filter((f) => f.endsWith('.png'))) {
    execFileSync('magick', [
      join(shots, file), '-fuzz', '2%', '-trim', '+repage',
      '-define', 'webp:method=6', '-quality', '88',
      join(dest, file.replace(/\.png$/, '.webp')),
    ]);
    console.log(`static/img/v2/${file.replace(/\.png$/, '.webp')}`);
  }
}
